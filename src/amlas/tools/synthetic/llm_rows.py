"""LLM-based row synthesis with classical fallback (spec sheet 2.6, master plan §7/C4).

The transcript's "derive rows from the old data + domain notes" ask. Rows are
generated by an **injectable** ``llm_fn(prompt)->str`` (mock in tests; Bedrock
Converse in production, mirroring ``imputation.llm_extrapolate``). The returned
rows are validated against the SynthesisSpec schema/constraints; rows that fail
validation are dropped. When no LLM is available, a deterministic classical
generator (``requirement.sample_from_spec``) materialises rows from the spec's
distributions so the tool always produces output.
"""

from __future__ import annotations

import json
from collections.abc import Callable
from pathlib import Path
from typing import Any

import pandas as pd
from strands import tool

from ...errors import tool_error_boundary
from .requirement import sample_from_spec, validate_synthesis_spec

LLMCallable = Callable[[str], str]


def _build_rows_prompt(spec: dict[str, Any], n: int, domain_notes: str, seed_rows: list[dict[str, Any]] | None) -> str:
    """Construct the row-generation prompt (schema + domain notes + seed examples)."""
    cols = [(c["name"], c.get("type", "numeric")) for c in spec.get("columns", [])]
    lines = [
        "You are a synthetic-data generator for long-lineage industrial records.",
        f"Generate exactly {n} realistic rows matching this schema:",
        json.dumps(cols, default=str),
        "",
        f"Domain notes: {domain_notes or '(none)'}",
        f"Constraints: {json.dumps(spec.get('constraints', []), default=str)}",
        f"Conditions: {json.dumps(spec.get('conditions', {}), default=str)}",
    ]
    if seed_rows:
        lines += ["", "Seed examples to imitate:", json.dumps(seed_rows[:10], default=str)]
    lines += [
        "",
        'Respond with ONLY a JSON array of row objects, e.g. [{"col":val,...}, ...].',
    ]
    return "\n".join(lines)


def _coerce_rows_to_schema(rows: list[dict[str, Any]], spec: dict[str, Any]) -> tuple[pd.DataFrame, int]:
    """Keep only rows that match the spec columns; coerce numeric types.

    Returns ``(valid_frame, n_dropped)``. A row is dropped if it is missing a
    spec column or a numeric column cannot be coerced to float.
    """
    col_specs = {c["name"]: c.get("type", "numeric") for c in spec.get("columns", [])}
    names = list(col_specs)
    valid: list[dict[str, Any]] = []
    dropped = 0
    for row in rows:
        if not isinstance(row, dict) or any(name not in row for name in names):
            dropped += 1
            continue
        coerced: dict[str, Any] = {}
        ok = True
        for name, ctype in col_specs.items():
            val = row[name]
            if ctype == "numeric":
                try:
                    coerced[name] = float(val)
                except (TypeError, ValueError):
                    ok = False
                    break
            else:
                coerced[name] = str(val)
        if ok:
            valid.append(coerced)
        else:
            dropped += 1
    frame = pd.DataFrame(valid, columns=names) if valid else pd.DataFrame(columns=names)
    return frame, dropped


def llm_synthesize_rows_core(
    spec: dict[str, Any],
    n: int,
    domain_notes: str = "",
    seed_rows: list[dict[str, Any]] | None = None,
    llm_fn: LLMCallable | None = None,
) -> dict[str, Any]:
    """Core LLM row synthesis (plain function; ``llm_fn`` injectable for isolated validation).

    Returns ``{"rows": DataFrame, "n_generated", "n_dropped", "source"}`` or an
    error dict. When ``llm_fn`` is None, falls back to the classical
    spec-distribution sampler.
    """
    ok, problems = validate_synthesis_spec(spec)
    if not ok:
        return {"success": False, "error": "invalid synthesis spec", "problems": problems}

    if llm_fn is None:
        frame = sample_from_spec({**spec, "volume": n})
        return {"rows": frame, "n_generated": len(frame), "n_dropped": 0, "source": "classical_fallback"}

    prompt = _build_rows_prompt(spec, n, domain_notes, seed_rows)
    try:
        raw = llm_fn(prompt)
    except Exception as e:
        # robust fallback: classical generator
        frame = sample_from_spec({**spec, "volume": n})
        return {
            "rows": frame,
            "n_generated": len(frame),
            "n_dropped": 0,
            "source": "classical_fallback",
            "warning": f"LLM call failed ({e}); used classical fallback",
        }

    parsed = _parse_json_array(raw)
    if parsed is None:
        frame = sample_from_spec({**spec, "volume": n})
        return {
            "rows": frame,
            "n_generated": len(frame),
            "n_dropped": 0,
            "source": "classical_fallback",
            "warning": "LLM response was not a valid JSON array; used classical fallback",
        }

    frame, dropped = _coerce_rows_to_schema(parsed, spec)
    return {"rows": frame, "n_generated": len(frame), "n_dropped": dropped, "source": "llm"}


def _parse_json_array(raw: str) -> list[dict[str, Any]] | None:
    raw = raw.strip()
    try:
        obj = json.loads(raw)
    except json.JSONDecodeError:
        start, end = raw.find("["), raw.rfind("]")
        if start != -1 and end != -1 and end > start:
            try:
                obj = json.loads(raw[start : end + 1])
            except json.JSONDecodeError:
                return None
        else:
            return None
    if isinstance(obj, dict) and "rows" in obj:
        obj = obj["rows"]
    return obj if isinstance(obj, list) else None


@tool
@tool_error_boundary(source="tools.synthetic.llm_rows")
def llm_synthesize_rows(
    spec_json: str,
    n: int,
    domain_notes: str = "",
    out_path: str | None = None,
) -> dict[str, Any]:
    """Generate synthetic rows from a SynthesisSpec via LLM (with classical fallback).

    Args:
        spec_json: JSON-encoded SynthesisSpec (from ``build_synthesis_spec``).
        n: Number of rows to generate.
        domain_notes: Free-text domain guidance (the steering "dial" notes).
        out_path: Optional path to write the generated CSV; defaults to a temp
            file next to nothing (returns rows inline if omitted).

    Returns:
        ``{"synthetic_path","rows","n_generated","n_dropped","source"}`` or
        ``{"success": False, "error": ...}``. (Production wires the Bedrock LLM
        via the Synthetic Data agent; offline validation inject a mock through
        ``llm_synthesize_rows_core``.)
    """
    try:
        spec = json.loads(spec_json) if isinstance(spec_json, str) else spec_json
    except json.JSONDecodeError as e:
        return {"success": False, "error": f"spec_json is not valid JSON: {e}"}

    result = llm_synthesize_rows_core(spec=spec, n=int(n), domain_notes=domain_notes, llm_fn=None)
    if result.get("success") is False:
        return result

    frame: pd.DataFrame = result["rows"]
    path = out_path or str(Path("synthetic_rows.csv").resolve())
    try:
        frame.to_csv(path, index=False)
    except Exception as e:
        return {"success": False, "error": f"failed to write synthetic rows: {e}"}

    return {
        "synthetic_path": path,
        "rows": len(frame),
        "n_generated": result["n_generated"],
        "n_dropped": result["n_dropped"],
        "source": result["source"],
    }
